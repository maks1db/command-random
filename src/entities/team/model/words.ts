const toPairs = (raw: string): WordPair[] =>
  raw
    .trim()
    .split('\n')
    .map((line) => {
      const [singular, plural] = line.split('|')
      return { singular, plural }
    })

export const ADJECTIVES: WordPair[] = toPairs(ADJECTIVES_RAW)
export const NOUNS: WordPair[] = toPairs(NOUNS_RAW)

// Генерирует уникальные названия команд вида «Быстрые Львы».
export function generateTeamNames(count: number): string[] {
  const used = new Set<string>()
  const names: string[] = []
  let guard = 0

  while (names.length < count && guard < 5000) {
    guard += 1
    const adjective = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)].plural
    const noun = NOUNS[Math.floor(Math.random() * NOUNS.length)].plural
    const name = `${adjective} ${noun}`
    if (used.has(name)) continue
    used.add(name)
    names.push(name)
  }

  while (names.length < count) {
    names.push(`Команда ${names.length + 1}`)
  }

  return names
}
